"""
slideshow_test.py - Checks the HTML slideshow (escaping, CSP hashes, structure), the seal, the
deck tool's html format, and the /open rules for HTML. No model needed.
Run from the project root:  python -m scripts.slideshow_test
"""

import base64
import hashlib
import re
import tempfile
from pathlib import Path

from PIL import Image

import danica.seal as seal
from danica.artifacts import is_openable
from danica.docgen import is_danica_file
from danica.markdown_doc import DocError, parse
from danica.slideshow import build_html
from danica.tools import run_tool
from danica.web import state_for
from danica.workspace import Workspace


def check(label: str, condition: bool) -> None:
    print(("PASS  " if condition else "FAIL  ") + label)
    assert condition, label


def sha(text: str) -> str:
    return "'sha256-" + base64.b64encode(hashlib.sha256(text.encode("utf-8")).digest()).decode("ascii") + "'"


OUTLINE = "\n".join([
    "# Pelican <b>Facts</b>", "A short talk", "Notes: welcome <everyone>", "",
    "## Diet", "", "- Fish", "  - Herring", "- **Bold** point", "Notes: speak slowly", "",
    "## Chart", "", "![Sales <chart>](charts/a.png)", "",
    "## Numbers", "", "Intro line", "", "| A | B |", "|---|---|", "| 1 | 2 |", "",
    "## Hostile", "", "Hello <script>alert(1)</script> and <img src=x onerror=alert(1)>", ""])

with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
    tmp = Path(tmp)
    seal.KEY_PATH = tmp / "seal.key"                       # never touch the real key in tests
    png = tmp / "a.png"
    Image.new("RGB", (300, 200), "red").save(png)

    out = tmp / "s.html"
    count, warnings = build_html(parse(OUTLINE), out, theme="clean", deck_title="", meta_title="Pelicans",
                                 sources=[("S1", "Pelican facts", "https://a.org/p")], image_for=lambda rel: png)
    page = out.read_text(encoding="utf-8")

    check("a slideshow with 4 slides plus a title and a Sources slide", count == 6 and page.count('<section class="slide') == 6)
    check("it is a complete HTML page", page.startswith("<!DOCTYPE html>") and page.rstrip().endswith("</html>"))
    check("slide titles are real headings", "<h2" in page and ">Diet</h2>" in page and ">Sources</h2>" in page)
    check("bullets, bold text and a table are there",
          "<strong>Bold</strong>" in page and "<th>A</th>" in page and "<td>2</td>" in page and "Herring" in page)
    check("speaker notes are saved, escaped", '<aside class="notes">speak slowly</aside>' in page
          and "welcome &lt;everyone&gt;" in page)
    check("the picture is embedded with escaped alt text",
          'src="data:image/png;base64,' in page and 'alt="Sales &lt;chart&gt;"' in page)
    check("the Sources slide lists the source", "[S1] Pelican facts - https://a.org/p" in page)
    check("no clean-build warnings", warnings == [])

    # --- escaping ---
    check("page text is escaped everywhere", "&lt;b&gt;Facts&lt;/b&gt;" in page and "&lt;script&gt;alert(1)&lt;/script&gt;" in page)
    check("no raw hostile tag survives", "<img src=x" not in page and "onerror=alert" not in page.replace("&lt;img src=x onerror=alert(1)&gt;", ""))
    check("the only script tag is Danica's own", page.count("<script") == 1 and page.count("</script>") == 1)
    check("nothing is loaded from the network", 'src="http' not in page and "href=" not in page and "@import" not in page)

    # --- the Content-Security-Policy, with its hashes recomputed from the file ---
    style = re.search(r"<style>(.*?)</style>", page, re.S).group(1)
    script = re.search(r"<script>(.*?)</script>", page, re.S).group(1)
    csp = re.search(r'http-equiv="Content-Security-Policy" content="([^"]+)"', page).group(1)
    check("the CSP forbids everything by default", "default-src 'none'" in csp and "img-src data:" in csp)
    check("the CSP allows exactly this style and this script, by hash", f"style-src {sha(style)}" in csp and f"script-src {sha(script)}" in csp)
    check("the CSP has no unsafe-inline", "unsafe" not in csp)

    # --- the seal ---
    check("a fresh slideshow verifies", seal.is_sealed_html(out) and is_danica_file(out))
    tampered = tmp / "t.html"
    tampered.write_text(page.replace("Diet", "Diet!", 1), encoding="utf-8")
    check("changing one character breaks the seal", not seal.is_sealed_html(tampered))
    forged = tmp / "f.html"
    forged.write_text('<meta name="generator" content="Generated by Danica"><meta name="danica-seal" content="">'
                      "<script>alert(1)</script>", encoding="utf-8")
    check("a page that only copies the marker is not sealed", not seal.is_sealed_html(forged) and not is_danica_file(forged))
    guess = tmp / "g.html"
    guess.write_text(page.replace('content="' + re.search(r'danica-seal" content="([0-9a-f]+)"', page).group(1) + '"', 'content="' + "0" * 64 + '"'),
                     encoding="utf-8")
    check("a guessed signature fails", not seal.is_sealed_html(guess))
    twice = tmp / "d.html"
    twice.write_text(page + page[page.index('<meta name="danica-seal"'):page.index('<meta name="danica-seal"') + 70], encoding="utf-8")
    check("a second seal tag fails", not seal.is_sealed_html(twice))
    check("a missing file is not sealed", not seal.is_sealed_html(tmp / "missing.html"))
    try:
        seal.seal_html("<p>no seal tag</p>")
        refused = False
    except ValueError:
        refused = True
    check("a page without a seal tag cannot be sealed", refused)
    old_key = seal.KEY_PATH.read_bytes()
    seal.KEY_PATH.write_bytes(b"x" * 32)
    check("a different key does not verify old files", not seal.is_sealed_html(out))
    seal.KEY_PATH.write_bytes(old_key)
    check("the original key verifies again", seal.is_sealed_html(out))

    # --- /open rules ---
    check("a sealed slideshow may be opened", is_openable(out))
    check("a forged or edited page may not", not is_openable(forged) and not is_openable(tampered))

    # --- themes, warnings and limits ---
    build_html(parse(OUTLINE), tmp / "d2.html", theme="dark", deck_title="", meta_title="t", sources=[], image_for=lambda r: png)
    check("the dark theme paints its colours", "#1E1E24" in (tmp / "d2.html").read_text(encoding="utf-8"))
    try:
        build_html(parse("## A\n"), tmp / "x.html", theme="neon", deck_title="", meta_title="t", sources=[], image_for=lambda r: png)
        bad_theme = False
    except DocError as e:
        bad_theme = "theme must be one of" in str(e)
    check("an unknown theme is refused", bad_theme)
    count, _ = build_html(parse("## Only\n\n- a\n"), tmp / "t2.html", theme="clean", deck_title="Given", meta_title="t", sources=[],
                          image_for=lambda r: png)
    check("a title slide is added from the title argument", count == 2 and ">Given</h1>" in (tmp / "t2.html").read_text(encoding="utf-8"))
    _, warnings = build_html(parse("## A\n\n![x](a.png)\n\n![y](a.png)\n"), tmp / "w.html", theme="clean", deck_title="", meta_title="t",
                             sources=[], image_for=lambda r: png)
    check("a second picture is dropped with a warning", any("only the first picture" in w for w in warnings))

    def missing(rel):
        raise DocError("image x: not found")

    _, warnings = build_html(parse("## A\n\n![x](nope.png)\n"), tmp / "m.html", theme="clean", deck_title="", meta_title="t",
                             sources=[], image_for=missing)
    check("a missing picture is a warning with a placeholder", warnings == ["image x: not found"]
          and "image not shown" in (tmp / "m.html").read_text(encoding="utf-8"))
    _, warnings = build_html(parse("## A\n\n" + "\n".join(f"- a long bullet point number {i} " + "word " * 12 for i in range(30))),
                             tmp / "o.html", theme="clean", deck_title="", meta_title="t", sources=[], image_for=lambda r: png)
    check("a slide with far too much text is flagged", any("lot of text" in w for w in warnings))

    import danica.slideshow as ss
    real = ss.MAX_EMBED_BYTES
    ss.MAX_EMBED_BYTES = 100
    try:
        try:
            build_html(parse("## A\n\n![x](a.png)\n"), tmp / "e.html", theme="clean", deck_title="", meta_title="t", sources=[], image_for=lambda r: png)
            embed_refused = False
        except DocError as e:
            embed_refused = "too large to embed" in str(e)
    finally:
        ss.MAX_EMBED_BYTES = real
    check("too many picture bytes are refused", embed_refused)
    for label, md in [("a table over 12 rows", "## T\n\n| A |\n|---|\n" + "\n".join("| x |" for _ in range(12))),
                      ("too many slides", "\n".join(f"## S{i}\n\n- a\n" for i in range(61))), ("no slides", "")]:
        try:
            build_html(parse(md) if md else [], tmp / "z.html", theme="clean", deck_title="", meta_title="t", sources=[], image_for=lambda r: png)
            refused = False
        except DocError:
            refused = True
        check(f"refused: {label}", refused)

    # --- the deck tool with format=html ---
    ws = Workspace(tmp / "ws")
    (ws.root / "charts").mkdir()
    (ws.root / "decks").mkdir()
    Image.new("RGB", (300, 200), "red").save(ws.root / "charts" / "a.png")
    state_for(ws).add("https://a.org/p", "https://a.org/p", "Pelican facts", ["p one"], [])

    def write(rel: str, content: str) -> None:
        (ws.root / rel).write_text(content, encoding="utf-8")

    write("decks/p.md", "# Pelicans\n\n## Diet\n\n- They eat fish [S1.1]\n\n## Chart\n\n![Chart](charts/a.png)\n")
    out_text = run_tool("deck", {"source": "decks/p.md", "format": "html", "theme": "warm"}, ws)
    html_path = ws.root / "decks" / "p.html"
    check("an HTML slideshow is made next to the outline", out_text.startswith("OK: saved decks/p.html") and "4 slides" in out_text
          and seal.is_sealed_html(html_path))
    check("the PowerPoint format still works", run_tool("deck", {"source": "decks/p.md"}, ws).startswith("OK: saved decks/p.pptx"))
    check("an unknown format is refused", run_tool("deck", {"source": "decks/p.md", "format": "exe"}, ws).startswith("ERROR"))
    check("re-making Danica's own slideshow replaces it", run_tool("deck", {"source": "decks/p.md", "format": "html"}, ws).startswith("OK"))
    write("decks/p.html", "<html>mine</html>")
    check("an HTML file Danica did not make is never replaced",
          "not made by Danica" in run_tool("deck", {"source": "decks/p.md", "format": "html"}, ws)
          and (ws.root / "decks" / "p.html").read_text(encoding="utf-8") == "<html>mine</html>")
    write("decks/bad.md", "## A\n\n- claim [S9.1]\n")
    check("a citation that points to nothing refuses the build",
          "point to nothing" in run_tool("deck", {"source": "decks/bad.md", "format": "html"}, ws)
          and not (ws.root / "decks" / "bad.html").exists())
    (ws.root / ".husky").mkdir()
    write(".husky/h.md", "## A\n")
    check("hook folders are never written to", "blocked" in run_tool("deck", {"source": ".husky/h.md", "format": "html"}, ws)
          and not (ws.root / ".husky" / "h.html").exists())

print("\nAll good.")