from rich.console import Console
from rich.text import Text

lines = [L1, L2, L3, L4, L5, L6, L7, L8, L9, L10, L11, L12, L13, L14]

# Order matters: later layers override earlier ones
layers = [
    (skin_color,  skin_map),
    (hair_color,  hair_map),
    (iris_color,  iris_map),
    (pupil_color, pupil_map),
    (blush_color, blush_map),
    (mouth_color, mouth_map),
]

def build_line(index: int) -> Text:
    text = Text(lines[index], no_wrap=True, overflow="crop")
    for color, cmap in layers:
        for start, end in cmap[index]:
            text.stylize(color, start, end)  # color hex works as a style
    return text

def render() -> None:
    console = Console()
    for i in range(len(lines)):
        console.print(build_line(i))

def ruler(console: Console) -> None:
    n = max(len(l) for l in lines)
    console.print("    " + "".join(str(i // 10) for i in range(n)))
    console.print("    " + "".join(str(i % 10) for i in range(n)))

def render_debug(only: str | None = None) -> None:
    """Print with a ruler and row numbers. Pass a layer name to see just that layer."""
    console = Console()
    ruler(console)
    names = ["skin", "hair", "iris", "pupil", "blush", "mouth"]
    for i in range(len(lines)):
        text = Text(lines[i], no_wrap=True, overflow="crop")
        for name, (color, cmap) in zip(names, layers):
            if only in (None, name):
                for start, end in cmap[i]:
                    text.stylize(color, start, end)
        console.print(Text(f"L{i+1:<3}") + text)

render_debug()          # everything
render_debug("mouth")   # only the mouth layer

if __name__ == "__main__":
    render()

