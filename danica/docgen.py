"""
docgen.py - Building .docx and .pdf files from parsed Markdown blocks (markdown_doc.py).

Every file carries the marker "Generated by Danica" (Word: the Comments property; PDF: the
Subject). is_danica_file() reads it, so the document tool and /open can tell Danica's own
files from yours. HONEST LIMIT: the marker is a guard against accidents, not against forgery.

PDF text uses Windows' Arial and Courier New (Latin, Greek and Cyrillic). Other scripts
and emoji are not covered. Without those fonts the built-in Helvetica/Courier are used.
All text is escaped before it reaches reportlab, so page text can never become markup.
"""

import os
import textwrap
from pathlib import Path
from xml.sax.saxutils import escape

from PIL import Image

from danica.markdown_doc import DocError, labelled
from danica.imageview import ImageError, check_image

MARKER = "Generated by Danica"
FONT_DIR = Path(os.environ.get("WINDIR", "C:\\Windows")) / "Fonts"
MAX_MARKER_SCAN = 20_000_000


def is_danica_file(path: Path) -> bool:
    """Was this .docx/.pdf made by Danica? (False for anything unreadable.)"""
    try:
        path = Path(path)
        if path.suffix.lower() == ".docx":
            from docx import Document
            return MARKER in (Document(str(path)).core_properties.comments or "")
        if path.suffix.lower() == ".pptx":
            from pptx import Presentation
            return MARKER in (Presentation(str(path)).core_properties.comments or "")
        if path.suffix.lower() == ".pdf" and path.stat().st_size <= MAX_MARKER_SCAN:
            return MARKER.encode("ascii") in path.read_bytes()
    except Exception:
        return False
    return False

def image_resolver(ws, md_path: Path):
    """image_for(rel) for the generators: the real path of a picture a Markdown file mentions,
    or DocError (which the generator turns into a warning). Looks in the workspace first, then
    next to the Markdown file. Same rules as <present>: inside the workspace, a real PNG/JPEG.
    Remote images are never downloaded."""
    md_dir = ws.display(Path(md_path).parent)

    def image_for(rel: str) -> Path:
        if "://" in rel:
            raise DocError(f"image {rel[:60]}: remote images are not downloaded")
        candidates = [rel] + ([f"{md_dir}/{rel}"] if md_dir != "." else [])
        last = "not found"
        for candidate in candidates:
            try:
                return check_image(ws, candidate)
            except ImageError as e:
                last = str(e)
        raise DocError(f"image {rel[:60]}: {last}")

    return image_for

def _image_size(path: Path) -> tuple[int, int]:
    with Image.open(path) as im:
        return im.size


# --------------------------------------------------------------------- Word

def _shade(paragraph, fill: str) -> None:
    """Grey background. Call this FIRST on a new paragraph: Word wants properties in order."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    paragraph._p.get_or_add_pPr().append(shd)


def _rule(paragraph) -> None:
    """A horizontal line (bottom border). Call this FIRST on a new paragraph."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    borders, bottom = OxmlElement("w:pBdr"), OxmlElement("w:bottom")
    for key, value in (("w:val", "single"), ("w:sz", "6"), ("w:space", "1"), ("w:color", "999999")):
        bottom.set(qn(key), value)
    borders.append(bottom)
    paragraph._p.get_or_add_pPr().append(borders)


def build_docx(blocks: list[dict], out: Path, *, title: str, meta_title: str,
               sources: list[tuple[str, str, str]], page: str, image_for) -> list[str]:
    """Write a Word file. Returns warnings (for example images that could not be added)."""
    try:
        from docx import Document
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.shared import Inches, Mm, Pt
    except ImportError:
        raise DocError("Word files need the python-docx package (pip install python-docx)")

    warnings: list[str] = []
    tmp = Path(out).with_name(Path(out).name + ".tmp")
    try:
        doc = Document()
        section = doc.sections[0]
        section.page_width, section.page_height = (Mm(210), Mm(297)) if page == "A4" else (Mm(215.9), Mm(279.4))
        for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
            setattr(section, side, Mm(22))
        doc.styles["Normal"].font.size = Pt(11)
        props = doc.core_properties
        props.title, props.author, props.comments = meta_title[:120], "Danica", MARKER

        def add_runs(paragraph, runs, bold: bool = False) -> None:
            for text, style in runs:
                run = paragraph.add_run(text)
                run.bold = bold or ("b" in style) or None      # None = inherit
                run.italic = ("i" in style) or None
                if "code" in style:
                    run.font.name, run.font.size = "Consolas", Pt(10)

        if title:
            doc.add_heading(title, level=0)
        for b in blocks:
            t = b["t"]
            if t == "h":
                add_runs(doc.add_heading("", level=b["level"]), b["runs"])
            elif t == "p":
                add_runs(doc.add_paragraph(), b["runs"])
            elif t in ("ul", "ol"):
                for level, label, runs in labelled(b):
                    p = doc.add_paragraph()
                    pf = p.paragraph_format
                    pf.left_indent, pf.first_line_indent = Inches(0.3 + 0.3 * level), Inches(-0.25)
                    pf.tab_stops.add_tab_stop(pf.left_indent)      # the text lines up after the marker
                    pf.space_after = Pt(2)
                    p.add_run(label + "\t")
                    add_runs(p, runs)
            elif t == "code":
                p = doc.add_paragraph()
                _shade(p, "F2F2F2")
                p.paragraph_format.left_indent = Inches(0.15)
                lines = b["text"].split("\n")
                for k, line in enumerate(lines):
                    run = p.add_run(line)
                    run.font.name, run.font.size = "Consolas", Pt(9)
                    if k < len(lines) - 1:
                        run.add_break()
            elif t == "quote":
                add_runs(doc.add_paragraph(style="Quote"), b["runs"])
            elif t == "hr":
                _rule(doc.add_paragraph())
            elif t == "table":
                ncols = len(b["header"])
                table = doc.add_table(rows=1 + len(b["rows"]), cols=ncols)
                table.style = "Table Grid"
                for c, runs in enumerate(b["header"]):
                    add_runs(table.rows[0].cells[c].paragraphs[0], runs, bold=True)
                for r, row in enumerate(b["rows"], start=1):
                    for c, runs in enumerate(row):
                        add_runs(table.rows[r].cells[c].paragraphs[0], runs)
                doc.add_paragraph()
            elif t == "img":
                try:
                    path = image_for(b["path"])
                    width_px = _image_size(path)[0]
                    doc.add_picture(str(path), width=Inches(min(6.0, max(2.0, width_px / 96))))
                    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
                    if b["alt"]:
                        caption = doc.add_paragraph()
                        caption.alignment = WD_ALIGN_PARAGRAPH.CENTER
                        run = caption.add_run(b["alt"])
                        run.italic, run.font.size = True, Pt(9)
                except DocError as e:
                    warnings.append(str(e))
                    doc.add_paragraph(f"[image not shown: {b['alt'] or b['path']}]")
                except Exception as e:
                    warnings.append(f"image {b['path']}: could not be added ({type(e).__name__})")
                    doc.add_paragraph(f"[image not shown: {b['alt'] or b['path']}]")

        if sources:                                               # built by the harness, never by the model
            doc.add_heading("Sources", level=1)
            for sid, stitle, url in sources:
                p = doc.add_paragraph()
                p.add_run(f"[{sid}] ").bold = True
                p.add_run(f"{stitle} - {url}")

        doc.save(str(tmp))
        os.replace(tmp, out)
    except DocError:
        raise
    except Exception as e:
        raise DocError(f"could not build the Word file ({type(e).__name__})")
    finally:
        if tmp.exists():
            tmp.unlink()
    return warnings


# ---------------------------------------------------------------------- PDF

_fonts_ready: tuple[str, str, str, str, str] | None = None


def _fonts() -> tuple[str, str, str, str, str]:
    """(regular, bold, italic, bold-italic, mono) font names, registered once."""
    global _fonts_ready
    if _fonts_ready:
        return _fonts_ready
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    files = {"DanicaSans": "arial.ttf", "DanicaSans-Bold": "arialbd.ttf", "DanicaSans-Italic": "ariali.ttf",
             "DanicaSans-BoldItalic": "arialbi.ttf", "DanicaMono": "cour.ttf"}
    try:
        for name, filename in files.items():
            pdfmetrics.registerFont(TTFont(name, str(FONT_DIR / filename)))
        pdfmetrics.registerFontFamily("DanicaSans", normal="DanicaSans", bold="DanicaSans-Bold",
                                      italic="DanicaSans-Italic", boldItalic="DanicaSans-BoldItalic")
        _fonts_ready = ("DanicaSans", "DanicaSans-Bold", "DanicaSans-Italic", "DanicaSans-BoldItalic", "DanicaMono")
    except Exception:                                             # fonts missing: the built-in ones
        _fonts_ready = ("Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique", "Courier")
    return _fonts_ready


def _markup(runs, mono: str) -> str:
    """Runs as reportlab markup. All text is escaped first: page text can never become tags."""
    out = []
    for text, style in runs:
        t = escape(text)
        if "code" in style:
            t = f'<font face="{mono}" size="9">{t}</font>'
        if "b" in style:
            t = f"<b>{t}</b>"
        if "i" in style:
            t = f"<i>{t}</i>"
        out.append(t)
    return "".join(out)


def build_pdf(blocks: list[dict], out: Path, *, title: str, meta_title: str,
              sources: list[tuple[str, str, str]], page: str, image_for) -> list[str]:
    """Write a PDF. Returns warnings (for example images that could not be added)."""
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4, LETTER
        from reportlab.lib.styles import ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.platypus import (HRFlowable, Image as RLImage, Paragraph, Preformatted,
                                        SimpleDocTemplate, Spacer, Table, TableStyle)
    except ImportError:
        raise DocError("PDF files need the reportlab package (pip install reportlab)")

    body, bold, italic, _, mono = _fonts()
    pagesize = A4 if page == "A4" else LETTER
    text_width = pagesize[0] - 4.4 * cm
    warnings: list[str] = []

    def style(name: str, **kw) -> ParagraphStyle:
        args = dict(fontName=body, fontSize=10.5, leading=15, spaceAfter=6)
        args.update(kw)
        return ParagraphStyle(name, **args)

    base = style("base")
    heading = {1: style("h1", fontName=bold, fontSize=20, leading=24, spaceBefore=14, spaceAfter=8, keepWithNext=1),
               2: style("h2", fontName=bold, fontSize=15, leading=19, spaceBefore=12, spaceAfter=6, keepWithNext=1),
               3: style("h3", fontName=bold, fontSize=12, leading=16, spaceBefore=10, spaceAfter=4, keepWithNext=1)}
    title_style = style("title", fontName=bold, fontSize=22, leading=27, alignment=1, spaceAfter=14)
    quote = style("quote", fontName=italic, leftIndent=14, textColor=colors.HexColor("#555555"))
    caption = style("caption", fontName=italic, fontSize=9, leading=12, alignment=1)
    code = ParagraphStyle("code", fontName=mono, fontSize=8.5, leading=11, backColor=colors.HexColor("#F2F2F2"),
                          borderPadding=4, leftIndent=6, spaceAfter=8)
    cell = style("cell", fontSize=9, leading=12, spaceAfter=0)
    cell_head = style("cellhead", fontName=bold, fontSize=9, leading=12, spaceAfter=0, textColor=colors.white)

    def list_style(level: int) -> ParagraphStyle:
        return style(f"li{level}", leftIndent=18 + 16 * level, bulletIndent=4 + 16 * level, spaceAfter=2)

    story: list = []
    if title:
        story.append(Paragraph(escape(title), title_style))
    for b in blocks:
        t = b["t"]
        if t == "h":
            story.append(Paragraph(_markup(b["runs"], mono), heading[b["level"]]))
        elif t == "p":
            story.append(Paragraph(_markup(b["runs"], mono), base))
        elif t in ("ul", "ol"):
            for level, label, runs in labelled(b):
                story.append(Paragraph(_markup(runs, mono), list_style(level), bulletText=label))
        elif t == "code":
            lines: list[str] = []
            for line in b["text"].split("\n"):                   # wrap long lines so they stay on the page
                lines += textwrap.wrap(line.expandtabs(4), 95, subsequent_indent="    ",
                                       replace_whitespace=False, drop_whitespace=False) or [""]
            story.append(Preformatted("\n".join(lines), code))
        elif t == "quote":
            story.append(Paragraph(_markup(b["runs"], mono), quote))
        elif t == "hr":
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#999999"),
                                    spaceBefore=6, spaceAfter=6))
        elif t == "table":
            ncols = len(b["header"])
            data = [[Paragraph(_markup(runs, mono), cell_head) for runs in b["header"]]]
            data += [[Paragraph(_markup(runs, mono), cell) for runs in row] for row in b["rows"]]
            table = Table(data, colWidths=[text_width / ncols] * ncols, repeatRows=1)
            table.setStyle(TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CCCCCC")),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0072B2")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
            story += [table, Spacer(1, 8)]
        elif t == "img":
            try:
                path = image_for(b["path"])
                w_px, h_px = _image_size(path)
                w, h = w_px * 0.75, h_px * 0.75                    # 96 dpi pixels to points
                scale = min(1.0, text_width / w, pagesize[1] * 0.55 / h)
                story.append(RLImage(str(path), width=w * scale, height=h * scale))
                if b["alt"]:
                    story.append(Paragraph(escape(b["alt"]), caption))
            except DocError as e:
                warnings.append(str(e))
                story.append(Paragraph(escape(f"[image not shown: {b['alt'] or b['path']}]"), base))
            except Exception as e:
                warnings.append(f"image {b['path']}: could not be added ({type(e).__name__})")
                story.append(Paragraph(escape(f"[image not shown: {b['alt'] or b['path']}]"), base))

    if sources:                                                   # built by the harness, never by the model
        story.append(Paragraph("Sources", heading[1]))
        for sid, stitle, url in sources:
            story.append(Paragraph(f"<b>[{escape(sid)}]</b> {escape(stitle)} - {escape(url)}", base))

    def footer(canvas, doc_) -> None:                             # the page number
        canvas.saveState()
        canvas.setFont(body, 8)
        canvas.setFillGray(0.4)
        canvas.drawCentredString(pagesize[0] / 2, 1.0 * cm, str(doc_.page))
        canvas.restoreState()

    tmp = Path(out).with_name(Path(out).name + ".tmp")
    try:
        pdf = SimpleDocTemplate(str(tmp), pagesize=pagesize, title=meta_title[:120], author="Danica",
                                subject=MARKER, creator="Danica", leftMargin=2.2 * cm, rightMargin=2.2 * cm,
                                topMargin=2.2 * cm, bottomMargin=2.2 * cm)
        pdf.build(story, onFirstPage=footer, onLaterPages=footer)
        os.replace(tmp, out)
    except Exception as e:
        raise DocError(f"could not build the PDF ({type(e).__name__})")
    finally:
        if tmp.exists():
            tmp.unlink()
    return warnings