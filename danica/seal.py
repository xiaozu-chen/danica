"""
seal.py - A signature that marks an HTML file as made by THIS Danica install.

A browser RUNS html, so the plain "Generated by Danica" marker is not enough to decide that a
file is safe to open or to replace: any model-written page could copy the marker. Instead each
slideshow carries an HMAC (HMAC-SHA256) of its own contents, made with a secret key stored in
%APPDATA%/Danica/seal.key, which the file tools cannot reach (path jail) and the shell must
ask about (outside-workspace prompt).

HONEST LIMITS: someone who can read your AppData folder can forge a seal. Deleting seal.key
makes every earlier slideshow stop verifying (they must be rebuilt).
"""

import hashlib
import hmac
import os
import re
import secrets
from pathlib import Path

from danica.config import APP_DIR

KEY_PATH = APP_DIR / "seal.key"
MAX_SEAL_FILE = 45_000_000
SEAL_RX = re.compile(r'(<meta name="danica-seal" content=")([0-9a-f]{0,64})(">)')


def _key() -> bytes:
    """The secret key (created on first use)."""
    try:
        key = KEY_PATH.read_bytes()
        if len(key) >= 32:
            return key
    except OSError:
        pass
    key = secrets.token_bytes(32)
    KEY_PATH.parent.mkdir(parents=True, exist_ok=True)
    tmp = KEY_PATH.with_suffix(".tmp")
    tmp.write_bytes(key)
    os.replace(tmp, KEY_PATH)
    return key


def _blank(html: str) -> str:
    """The page with its seal value removed (what the signature is computed over)."""
    return SEAL_RX.sub(lambda m: m.group(1) + m.group(3), html)


def _sign(html: str) -> str:
    return hmac.new(_key(), _blank(html).encode("utf-8"), hashlib.sha256).hexdigest()


def seal_html(html: str) -> str:
    """Fill in the page's (empty) seal tag. The page must contain exactly one."""
    if len(SEAL_RX.findall(html)) != 1:
        raise ValueError("the page must contain exactly one danica-seal tag")
    sig = _sign(html)
    return SEAL_RX.sub(lambda m: m.group(1) + sig + m.group(3), html)


def is_sealed_html(path: Path) -> bool:
    """True only if this install signed this exact file. Any change, or a forged marker, fails."""
    try:
        path = Path(path)
        if path.stat().st_size > MAX_SEAL_FILE:
            return False
        html = path.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return False
    found = SEAL_RX.findall(html)
    if len(found) != 1:
        return False
    return hmac.compare_digest(found[0][1], _sign(html))