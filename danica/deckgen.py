"""
deckgen.py - Building .pptx slide decks from parsed Markdown blocks (markdown_doc.py).

Outline rules:  "# Heading" = a title slide (text under it is the subtitle)
                "## Heading" = a content slide
                bullets (2 levels), short paragraphs, "### small heading", quotes, code blocks
                ONE picture or ONE table per slide (more are dropped with a warning)
                a paragraph starting "Notes:" = speaker notes
Layouts: text only = one column; text + picture = two columns; table = under the text; picture alone = centred.
Themes (clean, dark, warm, mono) are colours and fonts applied to every slide. 16:9.

HONEST LIMITS: text fitting is an ESTIMATE (check slides in PowerPoint); no animations,
transitions or custom master slides; the bullet and notes XML is written by hand, so open a
generated deck in PowerPoint once. Every file carries the marker "Generated by Danica".
"""

import math
import os
from collections.abc import Callable, Iterable
from pathlib import Path

from PIL import Image

from danica.docgen import MARKER
from danica.markdown_doc import DocError, labelled

HAVE_PPTX = None        # unknown until the first deck: python-pptx is slow to import and most sessions never build one


def _load_pptx() -> bool:
    """Import python-pptx the first time it is needed and put its names where the drawing helpers below find them."""
    global HAVE_PPTX, etree, Presentation, RGBColor, MSO_SHAPE, MSO_AUTO_SIZE
    global PP_ALIGN, qn, Emu, Inches, Pt
    if HAVE_PPTX is None:
        try:
            from lxml import etree
            from pptx import Presentation
            from pptx.dml.color import RGBColor
            from pptx.enum.shapes import MSO_SHAPE
            from pptx.enum.text import MSO_AUTO_SIZE, PP_ALIGN
            from pptx.oxml.ns import qn
            from pptx.util import Emu, Inches, Pt
            HAVE_PPTX = True
        except ImportError:
            HAVE_PPTX = False
    return HAVE_PPTX


MAX_SLIDES = 60
MAX_TABLE_ROWS = 12
MAX_CODE_LINES = 14
SOURCES_PER_SLIDE = 6
SIZES = (28, 24, 20, 18, 16, 14, 12)             # body font sizes to try, largest first
MONO = "Consolas"
BODY_L, BODY_T, BODY_W, BODY_H = 0.7, 1.8, 11.9, 4.9      # the body area, in inches (slide is 13.333 x 7.5)

THEMES = {
    "clean": dict(bg="FFFFFF", title="1F3A5F", text="222222", accent="0072B2", muted="777777",
                  cell="F2F6FA", cell_alt="E4ECF4", font="Calibri"),
    "dark": dict(bg="1E1E24", title="FFFFFF", text="E8E8E8", accent="E69F00", muted="9A9AA5",
                 cell="2A2A33", cell_alt="33333D", font="Calibri"),
    "warm": dict(bg="FBF5EA", title="5B3A29", text="3B2F2F", accent="C8553D", muted="8A7A6A",
                 cell="F3E8D6", cell_alt="EBDDC6", font="Calibri"),
    "mono": dict(bg="FFFFFF", title="000000", text="222222", accent="444444", muted="888888",
                 cell="F5F5F5", cell_alt="E8E8E8", font="Calibri"),
}


def plain(runs: Iterable[tuple[str, frozenset]]) -> str:
    """Join styled text runs into plain text."""
    return "".join(t for t, _ in runs)


# ------------------------------------------------------------ outline to slides

def split_slides(blocks: list[dict]) -> list[dict]:
    """Group blocks into slides: {"kind": "title"|"content", "title", "body": [blocks], "notes": [str]}."""
    slides: list[dict] = []
    cur = None
    for b in blocks:
        if b["t"] == "h" and b["level"] <= 2:
            cur = {"kind": "title" if b["level"] == 1 else "content", "title": plain(b["runs"]),
                   "body": [], "notes": []}
            slides.append(cur)
        elif b["t"] == "hr":
            continue
        elif cur is None:
            raise DocError("start the outline with a # title or a ## slide heading before any other text")
        elif b["t"] == "p" and plain(b["runs"]).lower().startswith("notes:"):
            cur["notes"].append(plain(b["runs"])[6:].strip())
        else:
            cur["body"].append(b)
    return slides


def text_items(blocks: list[dict]) -> list[tuple[int, float]]:
    """(characters, indent in points) of every text line, for estimating how much room a slide's text needs."""
    items: list[tuple[int, float]] = []
    for b in blocks:
        t = b["t"]
        if t == "p":
            items.append((len(plain(b["runs"])), 0))
        elif t == "h":
            items.append((len(plain(b["runs"])), 0))
        elif t == "quote":
            items.append((len(plain(b["runs"])), 22))
        elif t in ("ul", "ol"):
            for level, _, runs in labelled(b):
                items.append((len(plain(runs)) + 2, 25 + 25 * level))
        elif t == "code":
            for line in b["text"].split("\n")[:MAX_CODE_LINES]:
                items.append((min(len(line), 80), 0))
    return items


def estimate_height(
    items: list[tuple[int, float]], width_pts: float, size: int
) -> float:
    """Estimate rendered text height for slide layout."""
    total = 0.0
    for chars, indent in items:
        per_line = max(8.0, (width_pts - indent) / (size * 0.5))        # about 0.5 em per character
        lines = max(1, math.ceil(chars / per_line))
        total += lines * size * 1.25 + size * 0.45                      # the lines plus space after
    return total


def fit_size(
    items: list[tuple[int, float]], width_in: float, height_in: float
) -> tuple[int, bool]:
    """(font size, whether it is expected to fit). Falls back to the smallest size."""
    for size in SIZES:
        if estimate_height(items, width_in * 72, size) <= height_in * 72:
            return size, True
    return SIZES[-1], False


# ------------------------------------------------------------------ drawing

def _rgb(hex_color: str):
    return RGBColor.from_string(hex_color)


def _background(slide, theme: dict) -> None:
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = _rgb(theme["bg"])


def _bar(
    slide, theme: dict, left: float, top: float, width: float, height: float
) -> None:
    """The thin accent line under a title."""
    shape = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        Inches(left),
        Inches(top),
        Inches(width),
        Inches(height),
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = _rgb(theme["accent"])
    shape.line.fill.background()
    shape.shadow.inherit = False


def _add_runs(
    p,
    runs,
    size: float,
    color: str,
    theme: dict,
    bold: bool = False,
    italic: bool = False,
) -> None:
    for text, style in runs:
        r = p.add_run()
        r.text = text
        f = r.font
        f.size, f.name = Pt(size), theme["font"]
        f.color.rgb = _rgb(color)
        f.bold = True if (bold or "b" in style) else None
        f.italic = True if (italic or "i" in style) else None
        if "code" in style:
            f.name, f.size = MONO, Pt(max(10, size - 2))


def _indent(p, left_in: float, hang_in: float = 0.0) -> None:
    pPr = p._p.get_or_add_pPr()
    pPr.set("marL", str(int(Inches(left_in))))
    pPr.set("indent", str(-int(Inches(hang_in))))


def _bullet(p, char: str | None, level: int) -> None:
    """A real bullet (or none). Call AFTER the paragraph's spacing is set: the order of
    elements inside a paragraph's properties matters to PowerPoint."""
    _indent(p, 0.35 + 0.35 * level, 0.3 if char else 0.0)
    pPr = p._p.get_or_add_pPr()
    for tag in ("a:buNone", "a:buChar", "a:buAutoNum"):
        for old in pPr.findall(qn(tag)):
            pPr.remove(old)
    if char:
        etree.SubElement(pPr, qn("a:buChar")).set("char", char)
    else:
        etree.SubElement(pPr, qn("a:buNone"))


def _fill_text(tf, blocks: list[dict], size: int, theme: dict) -> None:
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.NONE
    state = {"first": True}

    def new_para():
        if state["first"]:
            state["first"] = False
            return tf.paragraphs[0]
        return tf.add_paragraph()

    for b in blocks:
        t = b["t"]
        if t == "p":
            p = new_para()
            p.space_after = Pt(size * 0.4)
            _add_runs(p, b["runs"], size, theme["text"], theme)
        elif t == "h":
            p = new_para()
            p.space_after = Pt(size * 0.4)
            _add_runs(p, b["runs"], size + 2, theme["accent"], theme, bold=True)
        elif t == "quote":
            p = new_para()
            p.space_after = Pt(size * 0.4)
            _add_runs(p, b["runs"], size, theme["muted"], theme, italic=True)
            _indent(p, 0.3)
        elif t in ("ul", "ol"):
            for level, label, runs in labelled(b):
                p = new_para()
                p.space_after = Pt(size * 0.3)
                if t == "ul":
                    _add_runs(p, runs, max(12, size - 2 * level), theme["text"], theme)
                    _bullet(p, label, level)
                else:                                          # numbers are written as text
                    _add_runs(p, [(label + " ", frozenset())] + list(runs), max(12, size - 2 * level),
                              theme["text"], theme)
                    _bullet(p, None, level)
        elif t == "code":
            for line in b["text"].split("\n")[:MAX_CODE_LINES]:
                p = new_para()
                p.space_after = Pt(2)
                shown = line if len(line) <= 80 else line[:79] + "…"
                _add_runs(p, [(shown, frozenset({"code"}))], max(11, size - 4), theme["text"], theme)


def _textbox(slide, left: float, top: float, width: float, height: float):
    return slide.shapes.add_textbox(
        Inches(left), Inches(top), Inches(width), Inches(height)
    ).text_frame


def _title_text(
    placeholder,
    text: str,
    theme: dict,
    size: int,
    left: float,
    top: float,
    width: float,
    height: float,
    center: bool = False,
) -> None:
    placeholder.left, placeholder.top = Inches(left), Inches(top)
    placeholder.width, placeholder.height = Inches(width), Inches(height)
    tf = placeholder.text_frame
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.NONE
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.CENTER if center else PP_ALIGN.LEFT
    _add_runs(p, [(text, frozenset())], size, theme["title"], theme, bold=True)


def _picture(
    slide,
    path: Path,
    alt: str,
    left: float,
    top: float,
    w_in: float,
    h_in: float,
    theme: dict,
) -> None:
    """A picture fitted inside the area (never stretched), centred, with the alt text as a caption."""
    caption_h = 0.45 if alt else 0.0
    with Image.open(path) as im:
        pw, ph = im.size
    scale = min(w_in / pw, (h_in - caption_h) / ph)
    wi, hi = pw * scale, ph * scale
    pic = slide.shapes.add_picture(
        str(path),
        Inches(left + (w_in - wi) / 2),
        Inches(top),
        Inches(wi),
        Inches(hi),
    )
    pic._element.nvPicPr.cNvPr.set("descr", alt[:200])              # alt text for screen readers
    if alt:
        tf = _textbox(slide, left, top + hi + 0.05, w_in, 0.4)
        p = tf.paragraphs[0]
        p.alignment = PP_ALIGN.CENTER
        _add_runs(p, [(alt, frozenset())], 12, theme["muted"], theme, italic=True)


def _table(
    slide, block: dict, left: float, top: float, width: float, height: float,
    theme: dict,
) -> None:
    rows, cols = 1 + len(block["rows"]), len(block["header"])
    size = 16 if rows <= 6 else 14 if rows <= 9 else 12
    row_h = size * 2.1 / 72
    shape = slide.shapes.add_table(
        rows,
        cols,
        Inches(left),
        Inches(top),
        Inches(width),
        Inches(min(height, rows * row_h)),
    )
    table = shape.table
    for r in range(rows):
        table.rows[r].height = Inches(row_h)
        for c in range(cols):
            runs = block["header"][c] if r == 0 else block["rows"][r - 1][c]
            cell = table.cell(r, c)
            cell.fill.solid()
            cell.fill.fore_color.rgb = _rgb(
                theme["accent"]
                if r == 0
                else theme["cell"]
                if r % 2
                else theme["cell_alt"]
            )
            _add_runs(
                cell.text_frame.paragraphs[0],
                runs,
                size,
                "FFFFFF" if r == 0 else theme["text"],
                theme,
                bold=(r == 0),
            )


def _page_number(slide, n: int, theme: dict) -> None:
    tf = _textbox(slide, 12.0, 6.95, 0.9, 0.35)
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.RIGHT
    _add_runs(p, [(str(n), frozenset())], 11, theme["muted"], theme)


def _title_slide(prs, spec: dict, theme: dict, warnings: list[str]) -> None:
    slide = prs.slides.add_slide(prs.slide_layouts[0])
    _background(slide, theme)
    _title_text(
        slide.shapes.title,
        spec["title"][:100],
        theme,
        44 if len(spec["title"]) <= 40 else 34,
        1.0,
        2.2,
        11.3,
        1.7,
    )
    _bar(slide, theme, 1.05, 4.05, 1.6, 0.08)
    subtitle = slide.placeholders[1]
    paragraphs = [b for b in spec["body"] if b["t"] == "p"]
    if len(paragraphs) != len(spec["body"]):
        warnings.append(f"title slide '{spec['title'][:30]}': only plain text is used under a # title")
    if paragraphs:
        subtitle.left, subtitle.top, subtitle.width, subtitle.height = (
            Inches(1.0),
            Inches(4.3),
            Inches(11.3),
            Inches(1.6),
        )
        tf = subtitle.text_frame
        tf.word_wrap = True
        tf.auto_size = MSO_AUTO_SIZE.NONE
        for k, b in enumerate(paragraphs[:3]):
            p = tf.paragraphs[0] if k == 0 else tf.add_paragraph()
            p.alignment = PP_ALIGN.LEFT
            _add_runs(p, b["runs"], 24, theme["muted"], theme)
    else:
        subtitle._element.getparent().remove(subtitle._element)     # no empty "Click to add subtitle" box
    if spec["notes"]:
        slide.notes_slide.notes_text_frame.text = "\n".join(spec["notes"])


def _content_slide(
    prs,
    spec: dict,
    n: int,
    theme: dict,
    image_for,
    warnings: list[str],
) -> None:
    slide = prs.slides.add_slide(prs.slide_layouts[5])               # "Title Only": a real title placeholder
    _background(slide, theme)
    title = spec["title"][:100]
    title_size = 32 if len(title) <= 50 else 26 if len(title) <= 80 else 22
    _title_text(
        slide.shapes.title, title, theme, title_size, BODY_L, 0.4, BODY_W, 1.0
    )
    _bar(slide, theme, BODY_L + 0.05, 1.42, 1.2, 0.07)
    label = f"slide {n} ('{title[:30]}')"

    visuals = [b for b in spec["body"] if b["t"] in ("img", "table")]
    text_blocks = [b for b in spec["body"] if b["t"] not in ("img", "table")]
    visual = visuals[0] if visuals else None
    if len(visuals) > 1:
            warnings.append(
                f"{label}: only the first picture or table is used "
                "(give the others their own slide)"
            )
    if visual and visual["t"] == "table" and len(visual["rows"]) > MAX_TABLE_ROWS - 1:
        raise DocError(f"{label}: a table holds at most {MAX_TABLE_ROWS} rows including the header "
                       f"(split it over two slides)")

    items = text_items(text_blocks)
    if visual and visual["t"] == "img":
        if text_blocks:                                              # text left, picture right
            text_box, visual_box = (
                (BODY_L, BODY_T, 6.4, BODY_H),
                (7.4, BODY_T, 5.2, BODY_H),
            )
        else:
            text_box, visual_box = None, (BODY_L, BODY_T, BODY_W, BODY_H)
    elif visual:                                                     # table under the text
        if text_blocks:
            text_box, visual_box = (
                (BODY_L, BODY_T, BODY_W, 1.7),
                (BODY_L, BODY_T + 1.9, BODY_W, BODY_H - 1.9),
            )
        else:
            text_box, visual_box = None, (BODY_L, BODY_T, BODY_W, BODY_H)
    else:
        text_box, visual_box = (BODY_L, BODY_T, BODY_W, BODY_H), None

    if text_box and text_blocks:
        size, fits = fit_size(items, text_box[2], text_box[3])
        if not fits:
            warnings.append(f"{label} has a lot of text and may overflow: split it into two slides")
        _fill_text(_textbox(slide, *text_box), text_blocks, size, theme)

    if visual and visual_box:
        if visual["t"] == "table":
            _table(slide, visual, *visual_box, theme)
        else:
            try:
                _picture(slide, image_for(visual["path"]), visual["alt"], *visual_box, theme)
            except DocError as e:
                warnings.append(str(e))
                tf = _textbox(slide, *visual_box)
                _add_runs(tf.paragraphs[0], [(f"[image not shown: {visual['alt'] or visual['path']}]", frozenset())],
                          16, theme["muted"], theme, italic=True)
            except Exception as e:
                warnings.append(f"image {visual['path']}: could not be added ({type(e).__name__})")

    _page_number(slide, n, theme)
    if spec["notes"]:
        slide.notes_slide.notes_text_frame.text = "\n".join(spec["notes"])


def build_pptx(
    blocks: list[dict],
    out: Path,
    *,
    theme: str,
    deck_title: str,
    meta_title: str,
    sources: list[tuple[str, str, str]],
    image_for: Callable[[str], Path],
) -> tuple[int, list[str]]:
    """Write a .pptx. Returns (number of slides, warnings)."""
    if not _load_pptx():
        raise DocError("slide decks need the python-pptx package (pip install python-pptx)")
    if theme not in THEMES:
        raise DocError("theme must be one of: " + ", ".join(THEMES))
    colours = THEMES[theme]

    slides = split_slides(blocks)
    if deck_title and not (slides and slides[0]["kind"] == "title"):
        slides.insert(0, {"kind": "title", "title": deck_title, "body": [], "notes": []})
    for k in range(0, len(sources), SOURCES_PER_SLIDE):              # built by the harness, never by the model
        chunk = sources[k:k + SOURCES_PER_SLIDE]
        items = [(0, [(f"[{sid}] {stitle} - {url}", frozenset())]) for sid, stitle, url in chunk]
        slides.append({"kind": "content", "title": "Sources" if k == 0 else f"Sources ({k // SOURCES_PER_SLIDE + 1})",
                       "body": [{"t": "ul", "items": items}], "notes": []})
    if not slides:
        raise DocError("the outline has no slides")
    if len(slides) > MAX_SLIDES:
        raise DocError(f"too many slides ({len(slides)}; the limit is {MAX_SLIDES})")

    warnings: list[str] = []
    tmp = Path(out).with_name(Path(out).name + ".tmp")
    try:
        prs = Presentation()
        prs.slide_width, prs.slide_height = Emu(12192000), Emu(6858000)       # 16:9
        props = prs.core_properties
        props.title, props.author, props.comments = meta_title[:120], "Danica", MARKER
        for n, spec in enumerate(slides, start=1):
            if spec["kind"] == "title":
                _title_slide(prs, spec, colours, warnings)
            else:
                _content_slide(prs, spec, n, colours, image_for, warnings)
        prs.save(str(tmp))
        os.replace(tmp, out)
    except DocError:
        raise
    except Exception as e:
        raise DocError(f"could not build the deck ({type(e).__name__})")
    finally:
        if tmp.exists():
            tmp.unlink()
    return len(slides), warnings
